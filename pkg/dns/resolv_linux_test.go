func TestResolvManager_ParseUpstreamServers(t *testing.T) {
	dir := t.TempDir()
	resolvPath := filepath.Join(dir, "resolv.conf")

	content := `# This is a comment
nameserver 10.0.0.1
nameserver 10.0.0.2
search example.com
nameserver 8.8.8.8
`
	if err := os.WriteFile(resolvPath, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}

	m := NewResolvManagerWithPaths(resolvPath, filepath.Join(dir, "backup"), logr.Discard())
	servers, err := m.ParseUpstreamServers()
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	expected := []string{"10.0.0.1:53", "10.0.0.2:53", "8.8.8.8:53"}
	if len(servers) != len(expected) {
		t.Fatalf("expected %d servers, got %d: %v", len(expected), len(servers), servers)
	}
	for i, s := range servers {
		if s != expected[i] {
			t.Fatalf("server[%d]: expected %s, got %s", i, expected[i], s)
		}
	}
}

func TestResolvManager_ManageAndRestore(t *testing.T) {
	dir := t.TempDir()
	resolvPath := filepath.Join(dir, "resolv.conf")
	backupDir := filepath.Join(dir, "backup")

	original := "nameserver 10.0.0.1\nnameserver 10.0.0.2\n"
	if err := os.WriteFile(resolvPath, []byte(original), 0644); err != nil {
		t.Fatal(err)
	}

	m := NewResolvManagerWithPaths(resolvPath, backupDir, logr.Discard())

	if err := m.ManageResolvConf("127.0.0.1:53"); err != nil {
		t.Fatalf("ManageResolvConf: %v", err)
	}

	data, err := os.ReadFile(resolvPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "nameserver 127.0.0.1") {
		t.Fatalf("resolv.conf should contain our nameserver, got: %s", data)
	}
	// Original nameservers should be preserved (prepend mode)
	if !strings.Contains(string(data), "10.0.0.1") {
		t.Fatalf("resolv.conf should still contain original nameserver, got: %s", data)
	}

	backupPath := filepath.Join(backupDir, backupFileName)
	backupData, err := os.ReadFile(backupPath)
	if err != nil {
		t.Fatalf("backup not found: %v", err)
	}
	if string(backupData) != original {
		t.Fatalf("backup content mismatch: got %q, want %q", backupData, original)
	}

	if err := m.RestoreResolvConf(); err != nil {
		t.Fatalf("RestoreResolvConf: %v", err)
	}

	data, err = os.ReadFile(resolvPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != original {
		t.Fatalf("after restore: got %q, want %q", data, original)
	}

	if _, err := os.Stat(backupPath); !os.IsNotExist(err) {
		t.Fatal("backup file should be removed after restore")
	}
}

func TestResolvManager_CrashRecovery(t *testing.T) {
	dir := t.TempDir()
	resolvPath := filepath.Join(dir, "resolv.conf")
	backupDir := filepath.Join(dir, "backup")

	original := "nameserver 192.168.1.1\n"
	managed := "# Generated by ngrokd - do not edit\nnameserver 127.0.0.1\n"

	os.MkdirAll(backupDir, 0755)
	os.WriteFile(resolvPath, []byte(managed), 0644)
	os.WriteFile(filepath.Join(backupDir, backupFileName), []byte(original), 0644)

	m := NewResolvManagerWithPaths(resolvPath, backupDir, logr.Discard())
	if err := m.RecoverFromCrash(); err != nil {
		t.Fatalf("RecoverFromCrash: %v", err)
	}

	data, err := os.ReadFile(resolvPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != original {
		t.Fatalf("after crash recovery: got %q, want %q", data, original)
	}
}

